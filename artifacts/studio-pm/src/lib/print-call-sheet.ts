import type { CallSheet, CrewInvite } from "@workspace/api-client-react";

function esc(s: string | null | undefined): string {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function fmtDate(iso: string): string {
  try {
    return new Date(iso + "T00:00:00").toLocaleDateString(undefined, {
      weekday: "long", year: "numeric", month: "long", day: "numeric",
    });
  } catch {
    return iso;
  }
}

function rateCell(c: CrewInvite): string {
  const kind = c.rateType === "half" ? "Half day" : "Full day";
  return c.dayRate != null ? `$${c.dayRate.toLocaleString()} (${kind})` : kind;
}

const STATUS_LABEL: Record<string, string> = {
  pending: "Pending", invited: "Invited", available: "Available",
  unavailable: "Not available", confirmed: "Confirmed",
};

/**
 * Open a standalone, print-optimized window for a call sheet and trigger the
 * browser print dialog (which doubles as Save-as-PDF). Self-contained HTML so
 * the SPA's styles and chrome never bleed into the printout.
 */
export function printCallSheet(sheet: CallSheet, projectName: string): void {
  const crew = sheet.crew ?? [];
  const heading = esc(sheet.title?.trim() || projectName);

  const meta: string[] = [];
  meta.push(`<div><span class="lbl">Date</span><span class="val">${esc(fmtDate(sheet.date))}</span></div>`);
  if (sheet.callTime) meta.push(`<div><span class="lbl">Call</span><span class="val">${esc(sheet.callTime)}</span></div>`);
  if (sheet.wrapTime) meta.push(`<div><span class="lbl">Wrap</span><span class="val">${esc(sheet.wrapTime)}</span></div>`);
  if (sheet.location) meta.push(`<div><span class="lbl">Location</span><span class="val">${esc(sheet.location)}</span></div>`);

  const billing = sheet.billingNote?.trim()
    ? `<div class="billing">${esc(sheet.billingNote)}</div>`
    : "";

  const rows = crew.length
    ? crew.map((c, i) => `
        <tr>
          <td class="num">${i + 1}</td>
          <td>${esc(c.position)}</td>
          <td>${esc(c.name)}</td>
          <td>${esc(c.email)}</td>
          <td>${esc(rateCell(c))}</td>
          <td>${esc(STATUS_LABEL[c.status] ?? c.status)}</td>
        </tr>`).join("")
    : `<tr><td colspan="6" class="empty">No crew listed.</td></tr>`;

  const notes = sheet.notes?.trim()
    ? `<div class="notes"><h2>Notes</h2><p>${esc(sheet.notes).replace(/\n/g, "<br>")}</p></div>`
    : "";

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>Call Sheet — ${heading} — ${esc(sheet.date)}</title>
<style>
  * { box-sizing: border-box; }
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #111; margin: 0; padding: 32px 36px; }
  header { border-bottom: 3px solid #111; padding-bottom: 14px; margin-bottom: 20px; }
  .kicker { font-size: 11px; letter-spacing: 0.18em; text-transform: uppercase; color: #666; margin: 0 0 4px; }
  h1 { font-size: 26px; margin: 0; }
  .meta { display: flex; flex-wrap: wrap; gap: 8px 28px; margin: 16px 0 18px; }
  .meta > div { display: flex; flex-direction: column; }
  .meta .lbl { font-size: 10px; letter-spacing: 0.14em; text-transform: uppercase; color: #888; }
  .meta .val { font-size: 14px; font-weight: 600; }
  .billing { background: #fff3cd; border: 1px solid #f0d27a; color: #7a5a00; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em; font-size: 12px; padding: 8px 12px; border-radius: 6px; margin-bottom: 18px; }
  table { width: 100%; border-collapse: collapse; font-size: 13px; }
  th { text-align: left; font-size: 10px; letter-spacing: 0.1em; text-transform: uppercase; color: #666; border-bottom: 2px solid #111; padding: 6px 8px; }
  td { padding: 7px 8px; border-bottom: 1px solid #ddd; vertical-align: top; }
  td.num { color: #999; width: 24px; }
  td.empty { text-align: center; color: #999; padding: 20px; }
  .notes { margin-top: 22px; }
  .notes h2 { font-size: 12px; letter-spacing: 0.12em; text-transform: uppercase; color: #666; border-bottom: 1px solid #ccc; padding-bottom: 4px; margin: 0 0 8px; }
  .notes p { font-size: 13px; line-height: 1.5; margin: 0; }
  footer { margin-top: 28px; padding-top: 10px; border-top: 1px solid #ccc; font-size: 10px; color: #999; }
  @media print { body { padding: 0; } @page { margin: 18mm; } }
</style>
</head>
<body>
  <header>
    <p class="kicker">Call Sheet${sheet.title?.trim() ? ` · ${esc(projectName)}` : ""}</p>
    <h1>${heading}</h1>
  </header>
  <div class="meta">${meta.join("")}</div>
  ${billing}
  <table>
    <thead>
      <tr><th>#</th><th>Position</th><th>Name</th><th>Email</th><th>Rate</th><th>Status</th></tr>
    </thead>
    <tbody>${rows}</tbody>
  </table>
  ${notes}
  <footer>Generated by Cue · ${esc(new Date().toLocaleString())}</footer>
  <script>window.onload = function(){ setTimeout(function(){ window.print(); }, 150); };</script>
</body>
</html>`;

  const w = window.open("", "_blank", "noopener,noreferrer,width=900,height=1000");
  if (!w) return;
  w.document.open();
  w.document.write(html);
  w.document.close();
}
